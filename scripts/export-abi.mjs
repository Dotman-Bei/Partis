// Exports the compiled PartisEventPass ABI to web/src/lib/abi.ts as a typed `as const` array.
// Run after `forge build`:  node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(
  readFileSync(join(root, "contracts/out/PartisEventPass.sol/PartisEventPass.json"), "utf8"),
);
const out = `// Generated by scripts/export-abi.mjs from contracts/src/PartisEventPass.sol — do not edit.
export const partisAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(join(root, "web/src/lib/abi.ts"), out);
console.log(`Wrote ${artifact.abi.length} ABI entries to web/src/lib/abi.ts`);
