// Exports the PartisEventPass ABI to web/src/lib/abi.ts as a typed `as const` array.
// Run after `forge build`:  node scripts/export-abi.mjs
//
// Only the parts the web app uses are shipped (it is in every page's JavaScript):
//   - functions referenced as `functionName: "…"` anywhere in web/src
//   - events referenced as `eventName: "…"`
//   - every custom error, so any revert decodes to a readable message
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(
  readFileSync(join(root, "contracts/out/PartisEventPass.sol/PartisEventPass.json"), "utf8"),
);

function sources(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return sources(p);
    return /\.(ts|tsx)$/.test(name) && !/\.test\.ts$/.test(name) && name !== "abi.ts" ? [p] : [];
  });
}

const used = new Map([
  ["function", new Set()],
  ["event", new Set()],
]);
for (const file of sources(join(root, "web/src"))) {
  const text = readFileSync(file, "utf8");
  for (const [, name] of text.matchAll(/functionName:\s*"(\w+)"/g)) used.get("function").add(name);
  for (const [, name] of text.matchAll(/eventName:\s*"(\w+)"/g)) used.get("event").add(name);
}

const abi = artifact.abi.filter(
  (item) => item.type === "error" || used.get(item.type)?.has(item.name),
);

const known = new Set(artifact.abi.map((i) => i.name));
const missing = [...used.get("function"), ...used.get("event")].filter((n) => !known.has(n));
if (missing.length) throw new Error(`web/src references unknown contract members: ${missing.join(", ")}`);

const out = `// Generated by scripts/export-abi.mjs from contracts/src/PartisEventPass.sol — do not edit.
// Contains only the functions and events the web app uses, plus all custom errors.
export const partisAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
writeFileSync(join(root, "web/src/lib/abi.ts"), out);
console.log(
  `Wrote ${abi.length}/${artifact.abi.length} ABI entries ` +
    `(${used.get("function").size} functions, ${used.get("event").size} events, all errors) to web/src/lib/abi.ts`,
);
